import { readFile, writeFile, mkdir, copyFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

// The userscript is the shared source of playback logic. Bundle it locally;
// extension users never load code from Tampermonkey or a remote script URL.
export async function buildExtension() {
  const source = await readFile(
    new URL("bili-together.user.js", import.meta.url),
    "utf8",
  );
  const version = source.match(/@version\s+(\S+)/)[1];
  const matches = [...source.matchAll(/@match\s+(\S+)/g)].map((x) => x[1]);
  let code = source.replace(
    /^\/\/ ==UserScript==[\s\S]*?\/\/ ==\/UserScript==\s*/,
    "",
  );
  for (const [before, after] of [
    ["GM_getValue", "getSetting"],
    ["GM_setValue", "setSetting"],
    ["GM_setClipboard", "copyText"],
  ])
    code = code.replaceAll(before, after);
  code = code.replace(
    'const host = document.createElement("div");',
    'if (document.getElementById("bt-extension-panel")) return;\n  const host = document.createElement("div");\n  host.id = "bt-extension-panel";',
  );
  code = code.replace(
    'copyText(link);\n    status("邀请链接已复制，发给朋友打开即可");',
    'copyText(link).then(() => status("邀请链接已复制，发给朋友打开即可")).catch(() => status("复制失败，请保持页面在前台后重试"));',
  );
  if (code.includes("GM_") || !code.includes("copyText(link).then"))
    throw Error("Shared script structure changed; update extension builder");
  const ending = code.lastIndexOf("})();");
  if (ending < 0) throw Error("Missing script ending");
  code =
    code.slice(0, ending) +
    `chrome.runtime.onMessage.addListener((message, sender, respond) => {
    if (sender.id !== chrome.runtime.id || message?.type !== "bt-show-panel") return;
    reveal();
    respond({ok:true});
  });\n` +
    code.slice(ending);
  const bundle = `// Generated by build-extension.mjs; all playback logic is bundled locally.\n(async () => {\n'use strict';\nconst settings = await chrome.storage.local.get(['room','autoHide']);\nconst getSetting = (key, fallback) => settings[key] ?? fallback;\nconst setSetting = (key, value) => {\n settings[key] = value;\n chrome.storage.local.set({[key]:value}).catch(() => {});\n};\nconst copyText = text => navigator.clipboard.writeText(text);\n${code}\n})().catch(error => console.error('B站一起看扩展启动失败',error));\n`;
  const output = new URL("extension/", import.meta.url);
  await mkdir(output, { recursive: true });
  await writeFile(new URL("content.js", output), bundle);
  const manifest = {
    manifest_version: 3,
    name: "B站一起看 · 多人同步",
    version,
    description:
      "多人同步播放、暂停、进度与倍速，支持稍后再看、跨视频持续同步和面板自动隐藏。",
    minimum_chrome_version: "109",
    permissions: ["storage", "clipboardWrite"],
    icons: { 16: "icons/16.png", 48: "icons/48.png", 128: "icons/128.png" },
    action: {
      default_title: "B站一起看",
      default_popup: "popup.html",
      default_icon: {
        16: "icons/16.png",
        48: "icons/48.png",
        128: "icons/128.png",
      },
    },
    content_scripts: [
      {
        matches,
        js: ["content.js"],
        run_at: "document_idle",
        all_frames: false,
      },
    ],
    homepage_url: "https://github.com/c18556210950-art/bili-together",
  };
  await writeFile(
    new URL("manifest.json", output),
    JSON.stringify(manifest, null, 2) + "\n",
  );
  await copyFile(
    new URL("LICENSE", import.meta.url),
    new URL("LICENSE", output),
  );
  return { version, matches, output: fileURLToPath(output) };
}
if (process.argv[1] === fileURLToPath(import.meta.url))
  console.log(await buildExtension());
